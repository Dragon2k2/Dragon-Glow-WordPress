"""Build the theme's self-hosted Material Symbols subset (development only)."""
import base64
import io
from pathlib import Path
import re
import urllib.request
from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[1]
THEME = ROOT / 'wp-content/themes/dragon-glow'
# Pin upstream so rebuilding does not silently change existing icons.
SOURCE = 'https://fonts.gstatic.com/s/materialsymbolsoutlined/v385/kJEhBvYX7BgnkSrUwT8OhrdQw4oELdPIeeII9v6oFsI.woff2'


def build():
    request = urllib.request.Request(SOURCE, headers={'User-Agent': 'Mozilla/5.0'})
    font = TTFont(io.BytesIO(urllib.request.urlopen(request, timeout=60).read()))
    # Include all names referenced by PHP, JS and CSS, including dynamic states,
    # data arrays and pseudo-elements. Match against upstream ligature names.
    words = set()
    codepoints = set()
    for path in THEME.rglob('*'):
        if path.suffix not in {'.php', '.js', '.css'} or path.name == 'material-symbols.css':
            continue
        text = path.read_text(encoding='utf-8')
        text = re.sub(r'/\*.*?\*/|^[ \t]*//[^\n]*', '', text, flags=re.S | re.M)
        words.update(re.findall(r'''["']([a-z][a-z_0-9]*)["']''', text))
        words.update(re.findall(r'>\s*([a-z][a-z_0-9]*)\s*<', text))
        codepoints.update(int(value, 16) for value in re.findall(r'\\([0-9a-fA-F]{4,6})\b', text))
    cmap = font.getBestCmap()
    reverse = {glyph: chr(code) for code, glyph in cmap.items() if code < 128}
    glyphs = {cmap[code] for code in codepoints if code in cmap}
    names = set()
    for lookup in font['GSUB'].table.LookupList.Lookup:
        for table in lookup.SubTable:
            table = getattr(table, 'ExtSubTable', table)
            for first, ligatures in getattr(table, 'ligatures', {}).items():
                for ligature in ligatures:
                    name = ''.join(reverse.get(glyph, '?') for glyph in [first] + ligature.Component)
                    if name in words:
                        glyphs.add(ligature.LigGlyph)
                        glyphs.update([first] + ligature.Component)
                        names.add(name)
    if not {'person', 'favorite', 'shopping_bag', 'menu', 'check', 'visibility_off'} <= names:
        raise RuntimeError('Required theme icons missing from upstream font')
    options = subset.Options()
    options.flavor = 'woff2'
    options.layout_features = ['*']
    options.layout_closure = False
    worker = subset.Subsetter(options=options)
    worker.populate(glyphs=glyphs)
    worker.subset(font)
    font.flavor = 'woff2'
    output = io.BytesIO()
    font.save(output)
    data = output.getvalue()
    target = THEME / 'assets/css/material-symbols.css'
    # An embedded local font eliminates the separate font request and its blank
    # font-display interval even with an empty browser cache / unavailable CDN.
    target.write_text('/* Dragon Glow — self-hosted Material Symbols Outlined.\n'
                      ' * Generated by scripts/build-icon-font.py; do not edit the payload.\n'
                      ' * Google Material Symbols, Apache-2.0; see ../fonts/LICENSE-material-symbols.txt.\n'
                      ' */\n@font-face {\n'
                      "    font-family: 'Material Symbols Outlined';\n"
                      '    font-style: normal;\n    font-weight: 100 700;\n'
                      '    font-display: block;\n'
                      "    src: url('data:font/woff2;base64," + base64.b64encode(data).decode() + "') format('woff2');\n}\n",
                      encoding='utf-8')
    license_text = urllib.request.urlopen('https://raw.githubusercontent.com/google/material-design-icons/master/LICENSE', timeout=60).read().decode('utf-8')
    license_path = THEME / 'assets/fonts/LICENSE-material-symbols.txt'
    license_path.parent.mkdir(parents=True, exist_ok=True)
    license_path.write_text(license_text, encoding='utf-8')
    print(f'Built {len(names)} icon ligatures + {len(codepoints)} CSS codepoints: {len(data):,} bytes WOFF2, {target.stat().st_size:,} bytes CSS')
    print('Icons: ' + ', '.join(sorted(names)))


if __name__ == '__main__':
    build()
