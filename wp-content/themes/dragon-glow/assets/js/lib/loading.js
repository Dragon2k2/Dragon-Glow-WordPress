/**
 * Dragon Glow — Loading State Helper
 *
 * Single place to show / hide the "in-flight" spinner on any clickable
 * element (button, link, icon button). Visuals live in main.css (.dg-loading).
 *
 * Exposes window.DGLoading:
 *   start(el)          → boolean  true if the loading state was applied
 *   stop(el)           → void
 *   isActive(el)       → boolean  use as a double-click guard in handlers
 *   track(el, promise) → Promise  start now, stop when the promise settles
 *   showPage()         → void     full-screen centred spinner (page navigation)
 *   hidePage()         → void     hide it (bfcache restore, failed navigation)
 *
 * Markup hooks (no per-page JS needed, work on AJAX-injected markup too):
 *   <a data-dg-loading-link>      navigates to another page: spinner on the link
 *                                 itself ONLY (no full-screen page loader).
 *   <form data-dg-loading-form>   native (non-AJAX) POST: spinner on the
 *                                 submit button ONLY once the form passes
 *                                 validation (no full-screen page loader).
 *   Links inside the site header (.dg-nav) and footer (.footer-main) without
 *   data-dg-loading-link: full-screen page loader only. Those links are
 *   generated by wp_nav_menu() / theme code, so they are matched by region
 *   instead of a per-link attribute.
 *
 * Accessibility: sets aria-busy + aria-disabled while loading. The element is
 * NOT given the `disabled` attribute here so keyboard focus is not dropped;
 * callers must guard re-entry with isActive().
 *
 * @package Dragon_Glow
 */

(function () {
	'use strict';

	var CLASS_NAME = 'dg-loading';

	/**
	 * Apply the loading state.
	 *
	 * The host's text colour is captured into --dg-loading-fg because the CSS
	 * hides the host's own text (color: transparent) and the spinner must
	 * still match it.
	 *
	 * @param {HTMLElement} el
	 * @return {boolean}
	 */
	function start(el) {
		if (!el || el.classList.contains(CLASS_NAME)) { return false; }

		el.style.setProperty('--dg-loading-fg', window.getComputedStyle(el).color);
		el.classList.add(CLASS_NAME);
		el.setAttribute('aria-busy', 'true');
		el.setAttribute('aria-disabled', 'true');
		return true;
	}

	/**
	 * Remove the loading state. Safe to call when not active.
	 *
	 * @param {HTMLElement} el
	 * @return {void}
	 */
	function stop(el) {
		if (!el || !el.classList.contains(CLASS_NAME)) { return; }

		el.classList.remove(CLASS_NAME);
		el.removeAttribute('aria-busy');
		el.removeAttribute('aria-disabled');
		el.style.removeProperty('--dg-loading-fg');
	}

	/**
	 * @param {HTMLElement} el
	 * @return {boolean}
	 */
	function isActive(el) {
		return !!el && el.classList.contains(CLASS_NAME);
	}

	/**
	 * Show loading until the promise settles, then pass the result through.
	 *
	 * @param {HTMLElement} el
	 * @param {Promise}     promise
	 * @return {Promise}
	 */
	function track(el, promise) {
		start(el);
		return promise.then(
			function (value) { stop(el); return value; },
			function (error) { stop(el); throw error; }
		);
	}

	var PAGE_LOADER_CLASS = 'dg-page-loader';
	var LINK_SELECTOR = 'a[data-dg-loading-link], .dg-nav a[href], .footer-main a[href]';
	var pageLoader = null;

	/**
	 * Lazily create the full-screen loader (created once, reused).
	 * role="status" makes screen readers announce the label when it activates.
	 *
	 * @return {HTMLElement}
	 */
	function getPageLoader() {
		if (pageLoader && document.body.contains(pageLoader)) { return pageLoader; }

		var i18n = window.dgLoadingI18n || {};

		pageLoader = document.createElement('div');
		pageLoader.className = PAGE_LOADER_CLASS;
		pageLoader.setAttribute('role', 'status');
		pageLoader.setAttribute('aria-live', 'polite');

		var spinner = document.createElement('div');
		spinner.className = PAGE_LOADER_CLASS + '__spinner';
		spinner.setAttribute('aria-hidden', 'true');

		var label = document.createElement('span');
		label.className = PAGE_LOADER_CLASS + '__label';
		label.textContent = i18n.label || 'Loading…';

		pageLoader.appendChild(spinner);
		pageLoader.appendChild(label);
		document.body.appendChild(pageLoader);

		return pageLoader;
	}

	/**
	 * Show the centred full-screen spinner (use right before a navigation).
	 * The CSS delays the fade-in, so very fast navigations never flash it.
	 *
	 * @return {void}
	 */
	function showPage() {
		var loader = getPageLoader();

		// Force a style flush so the opacity transition runs on first use.
		void loader.offsetWidth;
		loader.classList.add('is-active');
	}

	/**
	 * Hide the full-screen spinner. Safe to call when it was never shown.
	 *
	 * @return {void}
	 */
	function hidePage() {
		if (pageLoader) { pageLoader.classList.remove('is-active'); }
	}

	/**
	 * Navigation links: <a data-dg-loading-link href="..."> shows the spinner
	 * from click until the next page replaces this one (no page loader).
	 * Header and footer links without the attribute get the full-screen
	 * page loader instead.
	 *
	 * Skipped when the click does not navigate this tab (modifier keys,
	 * middle/right button, target other than _self, download, hash-only link)
	 * or when another handler already called preventDefault().
	 */
	document.addEventListener('click', function (event) {
		if (!event.target.closest) { return; }

		var link = event.target.closest(LINK_SELECTOR);
		if (!link) { return; }

		// Only links that opt in get a spinner on the link itself.
		var hasLinkSpinner = link.hasAttribute('data-dg-loading-link');

		if (hasLinkSpinner && isActive(link)) {
			// Second click while the page is already loading: ignore it.
			event.preventDefault();
			return;
		}

		var target = link.getAttribute('target');
		var opensHere = !target || target === '_self';

		if (
			event.defaultPrevented ||
			event.button !== 0 ||
			event.ctrlKey || event.metaKey || event.shiftKey || event.altKey ||
			!opensHere ||
			link.hasAttribute('download') ||
			!/^https?:$/.test(link.protocol) || // mailto:, tel:, javascript: never leave the page
			link.getAttribute('href') === '#' ||
			(link.hash && link.pathname === window.location.pathname && link.search === window.location.search)
		) {
			return;
		}

		// Opted-in links own their feedback (spinner on the link); region links
		// (header / footer) have no per-link feedback, so they get the page loader.
		if (hasLinkSpinner) {
			start(link);
		} else {
			showPage();
		}
	});

	/**
	 * Native form POST: <form data-dg-loading-form> shows the spinner on the
	 * submitting button until the server response replaces the page.
	 *
	 * The button is never given `disabled` (that would drop its name/value
	 * from the POST body, which WooCommerce handlers rely on). Runs in the
	 * bubble phase, so a form-level handler that called preventDefault()
	 * (e.g. client-side validation) is respected.
	 */
	document.addEventListener('submit', function (event) {
		var form = event.target;
		if (!form.matches || !form.matches('form[data-dg-loading-form]')) { return; }

		var button = event.submitter || form.querySelector('button[type="submit"]');
		if (!button) { return; }

		if (isActive(button)) {
			// Second submit (Enter key, double click) while the POST is in flight.
			event.preventDefault();
			return;
		}

		if (event.defaultPrevented) { return; }

		// The submit button owns the feedback; no full-screen page loader.
		start(button);
	});

	// Back/forward cache restores the page with the spinner still on: reset it.
	window.addEventListener('pageshow', function (event) {
		if (!event.persisted) { return; }

		hidePage();
		document.querySelectorAll(
			'a[data-dg-loading-link].' + CLASS_NAME + ', [data-dg-loading-form] .' + CLASS_NAME
		).forEach(stop);
	});

	window.DGLoading = {
		start:    start,
		stop:     stop,
		isActive: isActive,
		track:    track,
		showPage: showPage,
		hidePage: hidePage,
	};
})();
